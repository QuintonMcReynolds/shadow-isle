function gridToCanvas(grid, palette = PALETTE) {
  const h = grid.length, w = grid[0].length;
  const cv = document.createElement("canvas");
  cv.width = w; cv.height = h;
  const g = cv.getContext("2d");
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const k = grid[y][x];
      if (k !== "." && palette[k]) { g.fillStyle = palette[k]; g.fillRect(x, y, 1, 1); }
    }
  }
  return cv;
}

function mirror(grid) {
  return grid.map((r) => r.split("").reverse().join(""));
}

// Draw text with the bitmap font. colors: one color, or a function (charIndex) -> color.
function drawText(g, text, x, y, colors = "#fff", scale = 1, align = "left") {
  text = String(text).toUpperCase();
  const w = textWidth(text, scale);
  let cx = align === "center" ? Math.round(x - w / 2) : align === "right" ? x - w : x;
  let i = 0;
  for (const ch of text) {
    const glyph = FONT[ch] || FONT["?"];
    g.fillStyle = typeof colors === "function" ? colors(i, ch) : colors;
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (glyph[r][c] === "#") g.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += 6 * scale;
    i++;
  }
}

function textWidth(text, scale = 1) {
  return String(text).length * 6 * scale - scale;
}
